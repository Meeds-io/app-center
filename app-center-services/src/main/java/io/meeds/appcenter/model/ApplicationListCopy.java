package io.meeds.appcenter.model;

import java.util.List;
import java.util.Map;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * What a copy of a Shortcuts portlet window carries in its data.init
 * preference: the source window's header title and the applications it
 * created, by value, so that the copy owns its own once it is first rendered.
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
public class ApplicationListCopy {

  /** Header title labels, by language tag. */
  private Map<String, String>   headerTitles;

  private List<ApplicationCopy> applications;

}
